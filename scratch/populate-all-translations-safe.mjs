function safelyUpdateTranslationFile(filePath, isTh) {
  let content = fs.readFileSync(filePath, 'utf8');

  const sellerEntries = isTh ? sellerTh : sellerEn;
  const sellerAdsEntries = isTh ? sellerAdsTh : sellerAdsEn;
  const adminEntries = isTh ? adminTh : adminEn;
  const buyerObj = isTh ? buyerBlocksTh : buyerBlocksEn;

  // Insert missing keys into seller: { ... }
  content = insertIntoExistingBlock(content, 'seller', sellerEntries);

  // Insert missing keys into sellerAds: { ... }
  content = insertIntoExistingBlock(content, 'sellerAds', sellerAdsEntries);

  // Insert missing keys into admin: { ... }
  content = insertIntoExistingBlock(content, 'admin', adminEntries);

  // Append new top level buyer blocks if missing
  const lastBraceIdx = content.lastIndexOf('\n};');
  if (lastBraceIdx !== -1) {
    let appendStr = '\n';
    for (const [blockName, blockVal] of Object.entries(buyerObj)) {
      if (content.includes(`  ${blockName}: {`)) {
        // If block already exists, insert missing entries inside it
        content = insertIntoExistingBlock(content, blockName, blockVal);
      } else {
        appendStr += `  ${blockName}: {\n`;
        for (const [k, v] of Object.entries(blockVal)) {
          const formattedVal = typeof v === 'string' ? `'${v.replace(/'/g, "\\'")}'` : JSON.stringify(v);
          appendStr += `    ${k}: ${formattedVal},\n`;
        }
        appendStr += `  },\n`;
      }
    }

    if (appendStr.trim().length > 0) {
      content = content.slice(0, lastBraceIdx) + appendStr + content.slice(lastBraceIdx);
    }
  }

  fs.writeFileSync(filePath, content, 'utf8');
  console.log(`Successfully updated ${filePath}`);
}

function insertIntoExistingBlock(content, blockName, entriesObj) {
  const match = content.match(new RegExp(`  ${blockName}:\\s*\\{`));
  if (!match) return content;

  const insertIdx = match.index + match[0].length;
  // Get block content slice to check existing keys
  const blockSlice = content.slice(insertIdx, insertIdx + 20000);

  let newStr = '\n';
  for (const [k, v] of Object.entries(entriesObj)) {
    // Check if key already present in block slice
    const keyRegex = new RegExp(`\\b${k}:`);
    if (keyRegex.test(blockSlice)) continue; // skip existing key

    const formattedVal = typeof v === 'string' ? `'${v.replace(/'/g, "\\'")}'` : JSON.stringify(v);
    newStr += `    ${k}: ${formattedVal},\n`;
  }

  if (newStr === '\n') return content;
  return content.slice(0, insertIdx) + newStr + content.slice(insertIdx);
}

